"""
Real independent validation: EuRoC MAV V1_02 (Vicon Room 1, medium) -> the
real Ananta Meridian fusion/confidence/reliability engine.

This is NOT simulated. The data is:
  - v102_groundtruth.csv: real Vicon motion-capture ground truth (200 Hz,
    sub-millimeter accuracy), from the EuRoC MAV dataset (ASL, ETH Zurich).
  - v102_estimate.csv: a real, independently-computed visual(-inertial)
    odometry trajectory for the same flight (10 Hz), bundled as reference
    test data in the open-source `evo` trajectory-evaluation toolkit
    (github.com/MichaelGrupp/evo, GPLv3), originally sourced from EuRoC
    benchmark results. Neither file was generated by this project.

SOURCE / LICENSE NOTE: EuRoC MAV itself does not publish an explicit
license on its project page; it is the de facto standard academic
benchmark for VIO/SLAM research and is used here for internal engineering
validation only (not redistributed, not used to train anything). The
`evo` toolkit that bundles this specific pair of files is GPLv3-licensed;
only the small reference data files are used here, not evo's code. Cite
the EuRoC dataset (Burri et al., IJRR 2016) in any external-facing use of
this result.

IMPORTANT LIMITATION -- read before presenting this anywhere:
V102 is a SINGLE already-fused VIO trajectory, not separate raw sensor
streams. This project's real multi-sensor tests (DJI, marine, Arctic AIS,
NORCAT) feed several independent sensors into fuse_sensors() so it can
exercise disagreement detection and per-sensor reliability tracking. This
EuRoC run only has one sensor channel ("VIO"), so it validates the
confidence_engine's quality/freshness/reliability logic against REAL
measured error, but does NOT exercise multi-sensor disagreement -- that
remains validated only by the DJI/marine/NORCAT-shaped tests. Say so
alongside any claim drawn from this result.

Quality derivation: the raw estimate file has no published per-frame
confidence/covariance. Quality here is derived from the ESTIMATE'S OWN
frame-to-frame kinematics (linear speed, angular rate computed from
consecutive poses in v102_estimate.csv) -- a real, independently
computed signal, not derived from the ground truth (that would be
circular). This mirrors a hypothesis from the VIO literature: fast
motion and fast rotation measurably degrade visual feature tracking.
The reference speed/rate values used to scale this into a 0..1 quality
score are stated constants, not fit to this run.

MEASURED RESULT (not hypothetical -- this is what running the above
actually produced, reproducibly, on this real sequence):
    HIGH:   n=110, mean measured error = 0.112m
    MEDIUM: n=400, mean measured error = 0.081m
    LOW:    n=288, mean measured error = 0.070m
This is BACKWARDS from what a useful confidence signal should show --
steps the engine called HIGH confidence had, on average, MORE real
position error than steps it called LOW. The velocity/angular-rate
quality proxy does not predict this VIO system's actual accuracy on
this sequence, and may be inverted: near-stationary/slow segments can
be WORSE for monocular-style visual odometry than fast motion, because
small camera baselines make triangulation numerically ill-conditioned
(a known VO degeneracy) -- the opposite of the naive "slow = easy"
assumption this proxy was built on.

What this run DOES validate: the full pipeline (alignment, fuse_sensors,
compute_confidence, reliability_memory, ground-truth comparison) runs
correctly end-to-end against real, independently-collected data with
real ground truth -- the mechanics are sound. What it does NOT validate:
that this particular hand-built quality proxy produces a meaningful
confidence signal. That's a genuine, reproducible negative result, not
a bug -- and it's the strongest argument yet for why NORCAT (or any real
deployment) needs the actual nav system's own internal diagnostics
(covariance, feature count, match score, tracking state) rather than an
externally-guessed physics proxy. Do not cite the "HIGH/MEDIUM/LOW
percentages" from this run as evidence of anything working correctly --
only the pipeline mechanics and the alignment/RMSE methodology are the
reusable, defensible parts of this result.

Usage:
    python analyze_euroc_validation.py
"""

import csv
import json
import math
import os
import sys
from datetime import datetime

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)

from data_fusion.fusion_engine import fuse_sensors
from data_fusion.confidence_engine import compute_confidence
from data_fusion.reliability_memory import update_reliability_history
from ground_truth_compare import early_warning_summary

GT_PATH = os.path.join(_HERE, "v102_groundtruth.csv")
EST_PATH = os.path.join(_HERE, "v102_estimate.txt")

# Reference values for scaling kinematics into a quality score -- stated
# constants (not fit to this sequence): a MAV cruising at 2 m/s or
# rotating at 2 rad/s (~115 deg/s) is in a regime well documented in the
# VIO literature as degrading feature-tracking quality.
V_REF_MS = 2.0
W_REF_RADS = 2.0


def load_groundtruth(path):
    """Returns sorted list of (t_s, x, y, z)."""
    out = []
    with open(path) as f:
        reader = csv.reader(f)
        next(reader)  # header
        for row in reader:
            t = int(row[0]) / 1e9
            x, y, z = float(row[1]), float(row[2]), float(row[3])
            out.append((t, x, y, z))
    out.sort(key=lambda r: r[0])
    return out


def load_estimate(path):
    """TUM format: timestamp tx ty tz qx qy qz qw"""
    out = []
    with open(path) as f:
        for line in f:
            parts = line.split()
            if not parts:
                continue
            t = float(parts[0])
            x, y, z = float(parts[1]), float(parts[2]), float(parts[3])
            qx, qy, qz, qw = float(parts[4]), float(parts[5]), float(parts[6]), float(parts[7])
            out.append((t, x, y, z, qx, qy, qz, qw))
    return out


def interpolate_xyz(series, t, max_gap_s=0.05):
    """series: sorted list of (t,x,y,z). Linear-interpolate at time t."""
    import bisect
    times = [r[0] for r in series]
    i = bisect.bisect_left(times, t)
    if i == 0:
        return series[0][1:] if abs(series[0][0] - t) <= max_gap_s else None
    if i >= len(series):
        return series[-1][1:] if abs(series[-1][0] - t) <= max_gap_s else None
    t0, x0, y0, z0 = series[i - 1]
    t1, x1, y1, z1 = series[i]
    nearest = min(abs(t - t0), abs(t - t1))
    if nearest > max_gap_s:
        return None
    if t1 == t0:
        return (x0, y0, z0)
    frac = (t - t0) / (t1 - t0)
    return (x0 + frac * (x1 - x0), y0 + frac * (y1 - y0), z0 + frac * (z1 - z0))


def kabsch_align(est_points: np.ndarray, gt_points: np.ndarray):
    """Rigid-body (rotation + translation, scale=1) least-squares alignment
    mapping est_points onto gt_points -- standard practice for SLAM/VIO
    ATE evaluation (same method evo/TUM/KITTI benchmarks use), REQUIRED
    before comparing an estimated trajectory to ground truth: the
    estimator's own coordinate frame (wherever it initialized) has no
    reason to share an origin or orientation with the ground-truth frame,
    so raw unaligned distance is dominated by that fixed offset, not by
    real drift. Scale is fixed at 1.0 (not estimated) because this is a
    visual-INERTIAL estimate, which is metrically scaled by the IMU --
    unlike pure monocular VO, which would need scale alignment too."""
    est_centroid = est_points.mean(axis=0)
    gt_centroid = gt_points.mean(axis=0)
    est_c = est_points - est_centroid
    gt_c = gt_points - gt_centroid
    H = est_c.T @ gt_c
    U, S, Vt = np.linalg.svd(H)
    d = np.sign(np.linalg.det(Vt.T @ U.T))
    D = np.diag([1, 1, d])
    R = Vt.T @ D @ U.T
    t = gt_centroid - R @ est_centroid
    return R, t


def quat_angle_between(q1, q2):
    """Angle (rad) between two unit quaternions (qx,qy,qz,qw)."""
    dot = sum(a * b for a, b in zip(q1, q2))
    dot = max(-1.0, min(1.0, abs(dot)))
    return 2 * math.acos(dot)


def build_sensor_steps(estimate):
    """Build per-timestep single-sensor ('VIO') readings from the
    estimate's own frame-to-frame kinematics. Returns (steps, physical)."""
    steps = []
    physical = []
    for i, rec in enumerate(estimate):
        t, x, y, z, qx, qy, qz, qw = rec
        if i == 0:
            v, w = 0.0, 0.0
            dt = 0.1
        else:
            t0, x0, y0, z0, qx0, qy0, qz0, qw0 = estimate[i - 1]
            dt = max(t - t0, 1e-3)
            dist = math.sqrt((x - x0) ** 2 + (y - y0) ** 2 + (z - z0) ** 2)
            v = dist / dt
            ang = quat_angle_between((qx0, qy0, qz0, qw0), (qx, qy, qz, qw))
            w = ang / dt

        v_term = min(v / V_REF_MS, 1.0)
        w_term = min(w / W_REF_RADS, 1.0)
        quality = max(0.1, 1.0 - 0.5 * v_term - 0.5 * w_term)
        latency_ms = dt * 1000.0

        steps.append([{
            "sensor": "VIO",
            "detected": True,
            "quality": round(quality, 3),
            "latency": round(latency_ms, 1),
        }])
        physical.append({"t_s": t, "v_ms": round(v, 3), "w_rads": round(w, 3)})
    return steps, physical


def run():
    groundtruth = load_groundtruth(GT_PATH)
    estimate = load_estimate(EST_PATH)

    print("=" * 78)
    print("ANANTA MERIDIAN -- EuRoC MAV V1_02 Real-Data Validation")
    print("Real fusion_engine / confidence_engine / reliability_memory")
    print("Real Vicon ground truth + real published VIO estimate (not simulated)")
    print("=" * 78)
    print(f"Ground truth samples: {len(groundtruth)} (Vicon, 200Hz)")
    print(f"Estimate samples:     {len(estimate)} (VIO, ~10Hz)")

    steps, physical = build_sensor_steps(estimate)

    # --- Align estimate frame to ground-truth frame before computing error ---
    # (ground_truth.md note: raw unaligned error is dominated by the
    # estimator's arbitrary initial pose, not real drift -- see kabsch_align())
    gt_3d_sorted = groundtruth  # already (t, x, y, z), sorted
    est_matched, gt_matched, match_times = [], [], []
    for rec in estimate:
        t, x, y, z = rec[0], rec[1], rec[2], rec[3]
        gt_pt = interpolate_xyz(gt_3d_sorted, t)
        if gt_pt is None:
            continue
        est_matched.append((x, y, z))
        gt_matched.append(gt_pt)
        match_times.append(t)

    est_arr = np.array(est_matched)
    gt_arr = np.array(gt_matched)
    R, t_vec = kabsch_align(est_arr, gt_arr)
    aligned_est = (R @ est_arr.T).T + t_vec

    error_by_t = {}
    for i, mt in enumerate(match_times):
        err = float(np.linalg.norm(aligned_est[i] - gt_arr[i]))
        error_by_t[mt] = round(err, 3)

    pre_align_rmse = float(np.sqrt(np.mean(np.sum((est_arr - gt_arr) ** 2, axis=1))))
    post_align_rmse = float(np.sqrt(np.mean(np.sum((aligned_est - gt_arr) ** 2, axis=1))))
    print(f"\nFrame alignment: RMSE before={pre_align_rmse:.3f}m, after={post_align_rmse:.3f}m "
          f"(rigid rotation+translation, scale=1.0 -- standard ATE practice)")

    reliability_history = {}
    results = []
    print(f"\n{'t(s)':<10}{'VIO_q':<9}{'v(m/s)':<9}{'w(rad/s)':<10}{'Confidence':<12}{'MeasErr(m)':<12}{'Reasons'}")
    print("-" * 95)

    for i, sensors in enumerate(steps):
        fusion = fuse_sensors(sensors, reliability_history=reliability_history)
        confidence = compute_confidence(fusion, sensors)
        reliability_history = update_reliability_history(reliability_history, sensors)

        t = physical[i]["t_s"]
        err = error_by_t.get(t)
        reasons = "; ".join(confidence["reasons"][:2]) if confidence["reasons"] else "OK"
        err_str = f"{err:.3f}" if err is not None else "n/a"

        if i % 20 == 0 or i == len(steps) - 1:
            print(f"{t-estimate[0][0]:<10.1f}{sensors[0]['quality']:<9.3f}{physical[i]['v_ms']:<9.3f}"
                  f"{physical[i]['w_rads']:<10.3f}{confidence['level']:<12}{err_str:<12}{reasons}")

        results.append({
            "t_s": t,
            "sensors": sensors,
            "fusion": fusion,
            "confidence": confidence,
            "fused_position_error_m": err,
        })

    valid_results = [r for r in results if r["fused_position_error_m"] is not None]
    skipped = len(results) - len(valid_results)
    if skipped:
        print(f"\n({skipped} of {len(results)} steps had no ground-truth sample within tolerance -- excluded from error stats)")

    levels = [r["confidence"]["level"] for r in valid_results]
    total = len(levels)
    high, medium, low = levels.count("HIGH"), levels.count("MEDIUM"), levels.count("LOW")

    errs = [r["fused_position_error_m"] for r in valid_results]
    print("\n" + "=" * 78)
    print("CONFIDENCE SUMMARY (steps with matched ground truth)")
    print("=" * 78)
    print(f"Total matched steps: {total}")
    print(f"HIGH:   {high} ({high/total*100:.0f}%)")
    print(f"MEDIUM: {medium} ({medium/total*100:.0f}%)")
    print(f"LOW:    {low} ({low/total*100:.0f}%)")
    print(f"Measured error range: min={min(errs):.3f}m, max={max(errs):.3f}m, mean={sum(errs)/len(errs):.3f}m")

    confidence_trace = [{"t_s": r["t_s"], "level": r["confidence"]["level"]} for r in valid_results]
    error_series_out = [{"t_s": r["t_s"], "error_m": r["fused_position_error_m"]} for r in valid_results]
    # Error threshold set relative to this sequence's own error range (stated explicitly,
    # since there's no universal "acceptable drift" number without a mission spec).
    err_threshold = max(0.05, sum(errs) / len(errs))
    ew = early_warning_summary(confidence_trace, error_series_out, error_threshold_m=err_threshold)
    print(f"\nEarly-warning check (error threshold={err_threshold:.3f}m, set to this run's mean measured error):")
    if ew.get("warning_found"):
        print(f"  Confidence degraded off HIGH at t+{ew['warning_t_s']-estimate[0][0]:.1f}s "
              f"(measured error {ew['warning_error_m']:.3f}m); "
              f"final measured error {ew['final_error_m']:.3f}m at t+{ew['final_t_s']-estimate[0][0]:.1f}s; "
              f"lead time {ew['lead_time_min']:.2f} min.")
    else:
        print("  No sustained degradation crossing this threshold in this run.")

    print("\nMean measured error by confidence level (does the label correlate with real error?):")
    from collections import defaultdict
    by_level = defaultdict(list)
    for r in valid_results:
        by_level[r["confidence"]["level"]].append(r["fused_position_error_m"])
    for lvl in ["HIGH", "MEDIUM", "LOW"]:
        vals = by_level.get(lvl, [])
        if vals:
            print(f"  {lvl}: n={len(vals)}, mean_error={sum(vals)/len(vals):.4f}m, max_error={max(vals):.4f}m")

    print("\nReminder: VIO quality here is derived from the estimate's own motion kinematics")
    print("(a real, non-circular signal), not from raw per-sensor diagnostics the estimator")
    print("itself may have used internally -- we don't have access to those.")
    print("Single-sensor validation -- does not exercise multi-sensor disagreement logic.")

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    json_path = os.path.join(_HERE, f"{timestamp}_euroc_v102_validation.json")
    with open(json_path, "w") as f:
        json.dump({
            "meta": {
                "title": "Ananta Meridian -- EuRoC MAV V1_02 Real-Data Validation",
                "status": "REAL DATA -- Vicon ground truth + real published VIO estimate (EuRoC V1_02, via evo toolkit test data)",
                "engine": "data_fusion.fusion_engine / confidence_engine / reliability_memory (real, unmodified)",
                "limitation": "Single-sensor (VIO) validation; does not exercise multi-sensor disagreement logic.",
                "quality_derivation": "From estimate's own frame-to-frame speed/angular-rate, not raw sensor diagnostics.",
                "source": "EuRoC MAV dataset (Burri et al., IJRR 2016); estimate trajectory from evo (MichaelGrupp/evo, GPLv3) test data.",
            },
            "summary": {"high": high, "medium": medium, "low": low, "total": total,
                        "error_min_m": min(errs), "error_max_m": max(errs), "error_mean_m": sum(errs)/len(errs)},
            "early_warning": ew,
            "results": valid_results,
        }, f, indent=2)
    print(f"\nResults written:\n  {json_path}")
    return json_path


if __name__ == "__main__":
    run()
